create policy "Public can view approved submissions" on public.submissions for select using (status = 'approved');
create policy "Users view own submissions" on public.submissions for select to authenticated using (submitted_by = (select auth.uid()) or public.current_role() in ('national_admin','region_admin','district_admin','school_manager'));
create policy "Signed-in users submit own work" on public.submissions for insert to authenticated with check (submitted_by = (select auth.uid()) and status = 'pending');
create policy "Admins review submissions" on public.submissions for update to authenticated
 using (public.current_role() in ('national_admin','region_admin','district_admin','school_manager'))
 with check (public.current_role() in ('national_admin','region_admin','district_admin','school_manager'));

