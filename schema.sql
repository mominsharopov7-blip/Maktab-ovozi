create type public.user_role as enum ('student','school_manager','district_admin','region_admin','national_admin');
create type public.submission_status as enum ('pending','approved','rejected');

create table public.schools (
 id bigint generated by default as identity primary key,
 region text not null,
 district text not null,
 name text not null,
 school_code text unique,
 created_at timestamptz not null default now()
);

create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 role public.user_role not null default 'student',
 school_id bigint references public.schools(id),
 created_at timestamptz not null default now()
);

create table public.submissions (
 id uuid primary key default gen_random_uuid(),
 title text not null,
 description text,
 category text not null,
 media_url text,
 submitted_by uuid not null references auth.users(id) on delete cascade,
 status public.submission_status not null default 'pending',
 reviewed_by uuid references auth.users(id),
 reviewed_at timestamptz,
 created_at timestamptz not null default now()
);

create index submissions_status_created_idx on public.submissions(status, created_at desc);
create index profiles_school_idx on public.profiles(school_id);

create or replace function public.create_profile_for_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
 insert into public.profiles(id, full_name, role)
 values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), 'student');
 return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.create_profile_for_new_user();

alter table public.schools enable row level security;
alter table public.profiles enable row level security;
alter table public.submissions enable row level security;

create or replace function public.current_role()
returns public.user_role language sql stable security definer set search_path = '' as $$
 select role from public.profiles where id = (select auth.uid());
$$;
create or replace function public.current_school()
returns bigint language sql stable security definer set search_path = '' as $$
 select school_id from public.profiles where id = (select auth.uid());
$$;

create policy "Schools visible to everyone" on public.schools for select using (true);
create policy "Admins manage schools" on public.schools for all to authenticated
 using (public.current_role() in ('national_admin','region_admin','district_admin'))
 with check (public.current_role() in ('national_admin','region_admin','district_admin'));

create policy "Users view own profile" on public.profiles for select to authenticated using (id = (select auth.uid()) or public.current_role() in ('national_admin','region_admin','district_admin','school_manager'));
